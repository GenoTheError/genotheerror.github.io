// ==========================================
// УМНАЯ ОЧЕРЕДЬ ПРИМЕРОВ
// ==========================================
// Перемешивает список и выдаёт по одному без повторов,
// пока все не закончатся. Потом перемешивает заново.
// ==========================================

(function() {
    let очередь = [];
    let индекс = 0;
    
    function перемешать(arr) {
        const a = arr.slice();
        for (let i = a.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [a[i], a[j]] = [a[j], a[i]];
        }
        return a;
    }
    
    // Глобальная функция — берёт следующий пример без повторов
    window.следующийПример = function() {
        if (typeof ПРИМЕРЫ === 'undefined' || ПРИМЕРЫ.length === 0) {
            return null;
        }
        
        if (очередь.length === 0 || индекс >= очередь.length) {
            очередь = перемешать(ПРИМЕРЫ);
            индекс = 0;
        }
        
        const пример = очередь[индекс];
        индекс++;
        return пример;
    };
})();