// УМНАЯ ОЧЕРЕДЬ ФАКТОВ
// ==========================================
// Перемешивает список и выдаёт по одному без повторов,
// пока все не закончатся. Потом перемешивает заново.
// ==========================================

(function() {
    let очередь = [];
    let индекс = 0;
    
    function перемешать(arr) {
        const a = arr.slice();
        for (let i = a.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [a[i], a[j]] = [a[j], a[i]];
        }
        return a;
    }
    
    // Глобальная функция — берёт следующий факт без повторов
    window.следующийФакт = function() {
        if (typeof ФАКТЫ === 'undefined' || ФАКТЫ.length === 0) {
            return '❌ Факты не найдены.';
        }
        
        if (очередь.length === 0 || индекс >= очередь.length) {
            очередь = перемешать(ФАКТЫ);
            индекс = 0;
        }
        
        const факт = очередь[индекс];
        индекс++;
        return факт;
    };
})();